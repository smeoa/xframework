-- 主键补齐（历史库存在重复 id，需先订正再建主键；全部语句幂等）
DO $$
DECLARE
    v_before INTEGER;
    v_after  INTEGER;
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint con
        JOIN pg_class c ON c.oid = con.conrelid
        JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = 'public' AND c.relname = 'x_notification' AND con.contype = 'p'
    ) THEN
        SELECT count(*) INTO v_before FROM (
            SELECT id FROM x_notification GROUP BY id HAVING count(*) > 1
        ) q;
        IF v_before > 0 THEN
            ALTER TABLE x_notification ALTER COLUMN id SET GENERATED BY DEFAULT;
            WITH d AS (
                SELECT ctid, ROW_NUMBER() OVER (ORDER BY ctid) AS rn
                FROM x_notification a
                WHERE EXISTS (SELECT 1 FROM x_notification b WHERE b.id = a.id AND b.ctid < a.ctid)
            ), m AS (SELECT COALESCE(MAX(id), 0) AS mx FROM x_notification)
            UPDATE x_notification t SET id = m.mx + d.rn FROM d, m WHERE t.ctid = d.ctid;
            ALTER TABLE x_notification ALTER COLUMN id SET GENERATED ALWAYS;
            SELECT count(*) INTO v_after FROM (
                SELECT id FROM x_notification GROUP BY id HAVING count(*) > 1
            ) q;
            IF v_after > 0 THEN
                RAISE EXCEPTION 'x_notification 重复 id 订正失败，剩余 % 组', v_after;
            END IF;
        END IF;
        ALTER TABLE x_notification ADD CONSTRAINT pk_x_notification PRIMARY KEY (id);
        PERFORM setval(pg_get_serial_sequence('x_notification', 'id'), (SELECT MAX(id) FROM x_notification));
    END IF;
END $$;

-- 创建索引
CREATE INDEX IF NOT EXISTS idx_x_notification_type ON x_notification(type);
CREATE INDEX IF NOT EXISTS idx_x_notification_read ON x_notification(read);
CREATE INDEX IF NOT EXISTS idx_x_notification_timestamp ON x_notification(timestamp);

